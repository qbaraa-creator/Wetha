import type { ReactNode } from 'react';

/**
 * عزل القيم الرقمية عن اتجاه الفقرة العربية.
 *
 * في فقرة RTL تُعامل الفواصل المحايدة (– / · °) بين الأرقام على أنها عربية،
 * فينعكس ترتيب النطاق: «6–18» تُعرض «18–6» و«42–49–60%» تُعرض «60–49–42%».
 * `<bdi dir="ltr">` يجعل المحتوى مقطعًا مستقلًا يُرسم من اليسار لليمين
 * بينما يبقى موضعه داخل الجملة العربية سليمًا.
 *
 * تُلَف به القيمة ورموزها اللاتينية فقط (%، °، –)؛ أما الوحدات العربية
 * مثل «كم/س» فتبقى خارجه لتتبع اتجاه الجملة.
 */
export function Num({ children }: { children: ReactNode }) {
  return (
    <bdi dir="ltr" className="num">
      {children}
    </bdi>
  );
}

/**
 * نطاق زمني عربي مثل «6:00 ص–11:00 ص».
 *
 * هنا لا ينفع فرض LTR: صيغة الوقت تحمل «ص/م» العربية، ولفّها بـ LTR يقلبها
 * فتُقرأ «م 3:00». المطلوب عزل فقط — يبقى الترتيب عربيًا (الوقت الأول يمينًا)
 * بينما لا تتسرّب الفواصل المحايدة إلى ما حول النطاق.
 */
export function TimeRange({ children }: { children: ReactNode }) {
  return (
    <bdi dir="rtl" className="timerange">
      {children}
    </bdi>
  );
}
